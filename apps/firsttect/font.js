/* lit cells of a string as [col,row] pairs; each character is 6 columns wide */
function fontCells(str) {
  var out = [], s = String(str).toUpperCase();
  for (var i = 0; i < s.length; i++) {
    var g = FONT[s.charAt(i)] || FONT[' '];
    for (var r = 0; r < 7; r++) for (var c = 0; c < 5; c++) if (g[r] & (16 >> c)) out.push([i * 6 + c, r]);
  }
  return out;
}
